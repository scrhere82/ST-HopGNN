class DiffusionConv(nn.Module):

    def __init__(
        self,
        in_dim,
        out_dim,
        k=2
    ):

        super().__init__()

        self.k = k

        self.theta = nn.Linear(
            in_dim * k,
            out_dim
        )

    def forward(self, x, adj):

        """
        x:
            [B,N,C]
        """

        supports = []

        x0 = x

        supports.append(x0)

        x1 = torch.einsum(
            "nm,bmc->bnc",
            adj,
            x0
        )

        supports.append(x1)

        for _ in range(2, self.k):

            x2 = 2 * torch.einsum(
                "nm,bmc->bnc",
                adj,
                x1
            ) - x0

            supports.append(x2)

            x0, x1 = x1, x2

        out = torch.cat(
            supports,
            dim=-1
        )

        out = self.theta(out)

        return out

