class STGCNBlock(nn.Module):

    def __init__(self, hid):

        super().__init__()

        self.temp1 = TemporalConv(hid, hid)

        self.gcn = GCNConv(hid, hid)

        self.temp2 = TemporalConv(hid, hid)

        self.drop = nn.Dropout(0.3)

    def forward(self, x):

        B, T, N, H = x.shape

        x = x.permute(0,2,3,1)

        x = x.reshape(B*N, H, T)

        x = self.temp1(x)

        x_last = x[:, :, -1]

        x_last = self.gcn(
            x_last,
            edge_index,
            edge_weight
        )

        x_last = self.drop(x_last)

        x_last = x_last.view(B, N, H)

        x_last = x_last.permute(0,2,1)

        x_last = self.temp2(x_last)

        x_last = x_last.permute(0,2,1)

        return x_last

class STGCNModel(nn.Module):

    def __init__(self, num_sensors, hid=64):

        super().__init__()

        self.input_proj = nn.Linear(
            1,
            hid
        )

        self.block1 = STGCNBlock(hid)

        self.block2 = STGCNBlock(hid)

        self.fc = nn.Linear(hid, 1)

    def forward(self, x):

        x = x.unsqueeze(-1)

        x = self.input_proj(x)

        x = self.block1(x)

        x = self.block2(
            x.unsqueeze(1)
        )

        out = self.fc(x)

        return out.squeeze(-1)

