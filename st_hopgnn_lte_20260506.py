# ADAPTIVE GRAPH CONV
# ============================================================

class AVWGCN(nn.Module):

    def __init__(
        self,
        dim_in,
        dim_out,
        cheb_k,
        embed_dim
    ):

        super().__init__()

        self.cheb_k = cheb_k

        self.weights_pool = nn.Parameter(
            torch.FloatTensor(
                embed_dim,
                cheb_k,
                dim_in,
                dim_out
            )
        )

        self.bias_pool = nn.Parameter(
            torch.FloatTensor(
                embed_dim,
                dim_out
            )
        )

        nn.init.xavier_normal_(
            self.weights_pool
        )

        nn.init.xavier_normal_(
            self.bias_pool
        )

    def forward(
        self,
        x,
        node_emb
    ):

        """
        x:
            [B,N,C]
        """

        N = node_emb.shape[0]

        # ----------------------------------------------------
        # ADAPTIVE ADJ
        # ----------------------------------------------------

        supports = torch.softmax(
            torch.relu(
                torch.mm(
                    node_emb,
                    node_emb.t()
                )
            ),
            dim=1
        )

        support_set = [
            torch.eye(
                N,
                device=x.device
            ),
            supports
        ]

        # ----------------------------------------------------
        # CHEB SUPPORTS
        # ----------------------------------------------------

        for k in range(2, self.cheb_k):

            support_set.append(
                torch.matmul(
                    2 * supports,
                    support_set[-1]
                ) - support_set[-2]
            )

        supports = torch.stack(
            support_set,
            dim=0
        )

        # ----------------------------------------------------
        # GRAPH CONV
        # ----------------------------------------------------

        weights = torch.einsum(
            'nd,dkio->nkio',
            node_emb,
            self.weights_pool
        )

        bias = torch.matmul(
            node_emb,
            self.bias_pool
        )

        x_g = torch.einsum(
            "knm,bmc->bknc",
            supports,
            x
        )

        x_g = x_g.permute(
            0,
            2,
            1,
            3
        )

        out = torch.einsum(
            'bnki,nkio->bno',
            x_g,
            weights
        ) + bias

        return out

