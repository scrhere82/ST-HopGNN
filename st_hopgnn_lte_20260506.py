class AVWGCN(nn.Module):

    def __init__(
        self,
        dim_in,
        dim_out,
        cheb_k,
        embed_dim
    ):

        super().__init__()

        self.cheb_k = cheb_k

        self.weights_pool = nn.Parameter(
            torch.FloatTensor(
                embed_dim,
                cheb_k,
                dim_in,
                dim_out
            )
        )

        self.bias_pool = nn.Parameter(
            torch.FloatTensor(
                embed_dim,
                dim_out
            )
        )

        nn.init.xavier_normal_(
            self.weights_pool
        )

        nn.init.xavier_normal_(
            self.bias_pool
        )

    def forward(self, x, node_emb):

        N = node_emb.shape[0]

        supports = torch.softmax(
            torch.relu(
                torch.mm(
                    node_emb,
                    node_emb.t()
                )
            ),
            dim=1
        )

        support_set = [
            torch.eye(
                N,
                device=x.device
            ),
            supports
        ]

        for k in range(2, self.cheb_k):

            support_set.append(
                torch.matmul(
                    2 * supports,
                    support_set[-1]
                ) - support_set[-2]
            )

        supports = torch.stack(
            support_set,
            dim=0
        )

        weights = torch.einsum(
            'nd,dkio->nkio',
            node_emb,
            self.weights_pool
        )

        bias = torch.matmul(
            node_emb,
            self.bias_pool
        )

        x_g = torch.einsum(
            "knm,bmc->bknc",
            supports,
            x
        )

        x_g = x_g.permute(
            0,
            2,
            1,
            3
        )

        out = torch.einsum(
            'bnki,nkio->bno',
            x_g,
            weights
        ) + bias

        return out

class AGCRNCell(nn.Module):

    def __init__(
        self,
        num_nodes,
        dim_in,
        dim_out,
        cheb_k,
        embed_dim
    ):

        super().__init__()

        self.hidden_dim = dim_out

        self.gate = AVWGCN(
            dim_in + dim_out,
            2 * dim_out,
            cheb_k,
            embed_dim
        )

        self.update = AVWGCN(
            dim_in + dim_out,
            dim_out,
            cheb_k,
            embed_dim
        )

    def forward(self, x, state, node_emb):

        input_and_state = torch.cat(
            [x, state],
            dim=-1
        )

        z_r = torch.sigmoid(
            self.gate(
                input_and_state,
                node_emb
            )
        )

        z, r = torch.split(
            z_r,
            self.hidden_dim,
            dim=-1
        )

        candidate = torch.cat(
            [x, z * state],
            dim=-1
        )

        hc = torch.tanh(
            self.update(
                candidate,
                node_emb
            )
        )

        h = r * state + (1-r) * hc

        return h

class AGCRN(nn.Module):

    def __init__(
        self,
        num_nodes,
        hidden_dim=64,
        embed_dim=16
    ):

        super().__init__()

        self.hidden_dim = hidden_dim

        self.node_emb = nn.Parameter(
            torch.randn(
                num_nodes,
                embed_dim
            )
        )

        self.cell = AGCRNCell(
            num_nodes,
            1,
            hidden_dim,
            2,
            embed_dim
        )

        self.proj = nn.Linear(
            hidden_dim,
            1
        )

    def forward(self, x):

        B, T, N = x.shape

        h = torch.zeros(
            B,
            N,
            self.hidden_dim,
            device=x.device
        )

        for t in range(T):

            xt = x[:, t].unsqueeze(-1)

            h = self.cell(
                xt,
                h,
                self.node_emb
            )

        out = self.proj(h)

        return out.squeeze(-1)

