class TemporalConv(nn.Module):

    def __init__(
        self,
        in_ch,
        out_ch,
        kernel=3
    ):

        super().__init__()

        self.conv = nn.Conv1d(
            in_ch,
            out_ch,
            kernel,
            padding=1
        )

        self.relu = nn.ReLU()

    def forward(self, x):

        return self.relu(
            self.conv(x)
        )

# ============================================================
# STGCN BLOCK
# ============================================================

class STGCNBlock(nn.Module):

    def __init__(self, hid):

        super().__init__()

        self.temp1 = TemporalConv(
            hid,
            hid
        )

        self.gcn = GCNConv(
            hid,
            hid
        )

        self.temp2 = TemporalConv(
            hid,
            hid
        )

        self.drop = nn.Dropout(0.3)

    def forward(self, x):

        """
        x:
            [B,T,N,H]
        """

        B, T, N, H = x.shape

        # ----------------------------------------------------
        # TEMPORAL
        # ----------------------------------------------------

        x = x.permute(0,2,3,1)

        x = x.reshape(B*N, H, T)

        x = self.temp1(x)

        # ----------------------------------------------------
        # LAST TEMPORAL STATE
        # ----------------------------------------------------

        x_last = x[:, :, -1]

        # ----------------------------------------------------
        # GCN
        # ----------------------------------------------------

        x_last = self.gcn(
            x_last,
            edge_index,
            edge_weight
        )

        x_last = self.drop(x_last)

        # ----------------------------------------------------
        # TEMPORAL AGAIN
        # ----------------------------------------------------

        x_last = x_last.view(B, N, H)

        x_last = x_last.permute(0,2,1)

        x_last = self.temp2(x_last)

        x_last = x_last.permute(0,2,1)

        return x_last

