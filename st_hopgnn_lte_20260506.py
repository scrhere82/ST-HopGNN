class DiffusionConv(nn.Module):

    def __init__(self, in_dim, out_dim, k=2):

        super().__init__()

        self.theta = nn.Linear(
            in_dim * k,
            out_dim
        )

    def forward(self, x, adj):

        x1 = torch.einsum(
            "nm,bmc->bnc",
            adj,
            x
        )

        out = torch.cat(
            [x, x1],
            dim=-1
        )

        return self.theta(out)

class DCRNNCell(nn.Module):

    def __init__(self, hidden_dim=64):

        super().__init__()

        self.hidden_dim = hidden_dim

        self.gate = DiffusionConv(
            1 + hidden_dim,
            2 * hidden_dim
        )

        self.update = DiffusionConv(
            1 + hidden_dim,
            hidden_dim
        )

    def forward(self, x, h, adj):

        combined = torch.cat(
            [x, h],
            dim=-1
        )

        z_r = torch.sigmoid(
            self.gate(combined, adj)
        )

        z, r = torch.split(
            z_r,
            self.hidden_dim,
            dim=-1
        )

        candidate = torch.cat(
            [x, z * h],
            dim=-1
        )

        hc = torch.tanh(
            self.update(candidate, adj)
        )

        h = r * h + (1-r) * hc

        return h

class DCRNN(nn.Module):

    def __init__(self,
                 num_nodes,
                 hidden_dim=64):

        super().__init__()

        self.hidden_dim = hidden_dim

        self.cell = DCRNNCell(hidden_dim)

        self.proj = nn.Linear(
            hidden_dim,
            1
        )

    def forward(self, x):

        B, T, N = x.shape

        h = torch.zeros(
            B,
            N,
            self.hidden_dim,
            device=x.device
        )

        for t in range(T):

            xt = x[:, t].unsqueeze(-1)

            h = self.cell(
                xt,
                h,
                adj_dcrnn
            )

        out = self.proj(h)

        return out.squeeze(-1)

