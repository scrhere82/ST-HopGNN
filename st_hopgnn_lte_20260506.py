class TemporalBlock(nn.Module):

    def __init__(
        self,
        in_ch,
        out_ch,
        kernel_size,
        dilation
    ):

        super().__init__()

        padding = (kernel_size - 1) * dilation

        self.conv1 = nn.Conv1d(
            in_ch,
            out_ch,
            kernel_size,
            padding=padding,
            dilation=dilation
        )

        self.relu1 = nn.ReLU()

        self.conv2 = nn.Conv1d(
            out_ch,
            out_ch,
            kernel_size,
            padding=padding,
            dilation=dilation
        )

        self.relu2 = nn.ReLU()

        self.downsample = (
            nn.Conv1d(in_ch, out_ch, 1)
            if in_ch != out_ch
            else None
        )

    def forward(self, x):

        out = self.conv1(x)

        out = out[:, :, :-self.conv1.padding[0]]

        out = self.relu1(out)

        out = self.conv2(out)

        out = out[:, :, :-self.conv2.padding[0]]

        out = self.relu2(out)

        res = x if self.downsample is None \
              else self.downsample(x)

        return out + res

class TCNModel(nn.Module):

    def __init__(self, num_sensors, hid=64):

        super().__init__()

        self.network = nn.Sequential(

            TemporalBlock(
                num_sensors,
                hid,
                2,
                1
            ),

            TemporalBlock(
                hid,
                hid,
                2,
                2
            )
        )

        self.fc = nn.Sequential(

            nn.Linear(hid, 64),

            nn.ReLU(),

            nn.Linear(64, num_sensors)
        )

    def forward(self, x):

        x = x.permute(0, 2, 1)

        out = self.network(x)

        out = out[:, :, -1]

        return self.fc(out)

