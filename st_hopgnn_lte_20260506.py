# ST-HopGNN
# ============================================================

class STHopGNN(nn.Module):

    def __init__(self, nodes):

        super().__init__()

        self.esn = ESN(1, HID)

        self.gnn = HopGNN(HID, HOPS)

        # ----------------------------------------------------
        # ADJ
        # ----------------------------------------------------

        if GRAPH_MODE == "learned":

            self.adj = nn.Parameter(
                torch.rand(nodes, nodes)*0.1
            )

        else:

            fixed_adj = GRAPH_BANK[GRAPH_MODE]

            self.adj = torch.tensor(
                fixed_adj,
                dtype=torch.float32
            )

        self.drop = nn.Dropout(0.35)

        self.recon = nn.Linear(HID, 1)

    def forward(self, x):

        last = x[:, -1, :].unsqueeze(-1)

        feats = self.esn(last)

        h = self.gnn(feats, self.adj)

        out = self.recon(h).squeeze(-1)

        return out

