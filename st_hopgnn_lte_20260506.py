class DiffusionConv(nn.Module):

    def __init__(self, in_dim, out_dim, k=2):

        super().__init__()

        self.k = k

        self.theta = nn.Linear(
            in_dim * k,
            out_dim
        )

    def forward(self, x, adj):

        supports = []

        x0 = x

        supports.append(x0)

        x1 = torch.einsum(
            "nm,bmc->bnc",
            adj,
            x0
        )

        supports.append(x1)

        out = torch.cat(
            supports,
            dim=-1
        )

        out = self.theta(out)

        return out

class DCRNNCell(nn.Module):

    def __init__(self,
                 input_dim,
                 hidden_dim,
                 k=2):

        super().__init__()

        self.hidden_dim = hidden_dim

        self.gate = DiffusionConv(
            input_dim + hidden_dim,
            2 * hidden_dim,
            k
        )

        self.update = DiffusionConv(
            input_dim + hidden_dim,
            hidden_dim,
            k
        )

    def forward(self, x, h, adj):

        combined = torch.cat(
            [x, h],
            dim=-1
        )

        z_r = torch.sigmoid(
            self.gate(combined, adj)
        )

        z, r = torch.split(
            z_r,
            self.hidden_dim,
            dim=-1
        )

        candidate = torch.cat(
            [x, z * h],
            dim=-1
        )

        hc = torch.tanh(
            self.update(candidate, adj)
        )

        h = r * h + (1-r) * hc

        return h

class DCRNN(nn.Module):

    def __init__(self,
                 num_nodes,
                 hidden_dim=64,
                 k=2):

        super().__init__()

        self.hidden_dim = hidden_dim

        self.cell = DCRNNCell(
            1,
            hidden_dim,
            k
        )

        self.proj = nn.Linear(
            hidden_dim,
            1
        )

    def forward(self, x):

        B, T, N = x.shape

        h = torch.zeros(
            B,
            N,
            self.hidden_dim,
            device=x.device
        )

        for t in range(T):

            xt = x[:, t].unsqueeze(-1)

            h = self.cell(
                xt,
                h,
                adj
            )

        out = self.proj(h)

        return out.squeeze(-1)

