# ============================================================
# GRAPH LEARNING
# ============================================================

class GraphLearning(nn.Module):

    def __init__(
        self,
        num_nodes,
        emb_dim=16,
        topk=8
    ):

        super().__init__()

        self.emb1 = nn.Parameter(
            torch.randn(num_nodes, emb_dim)
        )

        self.emb2 = nn.Parameter(
            torch.randn(num_nodes, emb_dim)
        )

        self.topk = topk

    def forward(self):

        # ----------------------------------------------------
        # LEARN ADJ
        # ----------------------------------------------------

        adj = torch.relu(
            torch.mm(
                self.emb1,
                self.emb2.t()
            )
        )

        # ----------------------------------------------------
        # TOP-K SPARSIFICATION
        # ----------------------------------------------------

        mask = torch.zeros_like(adj)

        vals, idx = torch.topk(
            adj,
            self.topk,
            dim=1
        )

        mask.scatter_(1, idx, 1.0)

        adj = adj * mask

        # ----------------------------------------------------
        # NORMALIZE
        # ----------------------------------------------------

        adj = adj / (
            adj.sum(dim=1, keepdim=True) + 1e-6
        )

        return adj

# ============================================================
# MIXHOP GRAPH CONV
# ============================================================

class MixHopLayer(nn.Module):

    def __init__(
        self,
        in_dim,
        out_dim
    ):

        super().__init__()

        self.lin1 = nn.Linear(
            in_dim,
            out_dim
        )

        self.lin2 = nn.Linear(
            in_dim,
            out_dim
        )

    def forward(
        self,
        x,
        adj
    ):

        """
        x:
            [B,N,C]
        """

        hop1 = torch.einsum(
            "nm,bmc->bnc",
            adj,
            x
        )

        hop2 = torch.einsum(
            "nm,bmc->bnc",
            adj,
            hop1
        )

        out = self.lin1(hop1) + \
              self.lin2(hop2)

        return out

# ============================================================
# TEMPORAL CONV
# ============================================================

class TemporalConv(nn.Module):

    def __init__(
        self,
        channels
    ):

        super().__init__()

        self.conv = nn.Conv1d(
            channels,
            channels,
            kernel_size=3,
            padding=1
        )

        self.relu = nn.ReLU()

    def forward(self, x):

        return self.relu(
            self.conv(x)
        )

# ============================================================
# MTGNN MODEL
# ============================================================

class MTGNN(nn.Module):

    def __init__(
        self,
        num_nodes,
        hid=64
    ):

        super().__init__()

        self.graph_learner = GraphLearning(
            num_nodes,
            emb_dim=NODE_EMB,
            topk=TOPK
        )

        self.input_proj = nn.Linear(
            1,
            hid
        )

        self.temp1 = TemporalConv(hid)

        self.graph1 = MixHopLayer(
            hid,
            hid
        )

        self.temp2 = TemporalConv(hid)

        self.graph2 = MixHopLayer(
            hid,
            hid
        )

        self.drop = nn.Dropout(0.3)

        self.fc = nn.Linear(
            hid,
            1
        )

    def forward(self, x):

        """
        x:
            [B,T,N]
        """

        B, T, N = x.shape

        # ----------------------------------------------------
        # LEARN GRAPH
        # ----------------------------------------------------

        adj = self.graph_learner()

        # ----------------------------------------------------
        # INPUT PROJ
        # ----------------------------------------------------

        x = x.unsqueeze(-1)

        x = self.input_proj(x)

        # ----------------------------------------------------
        # TEMPORAL
        # ----------------------------------------------------

        x = x.permute(0,2,3,1)

        x = x.reshape(B*N, -1, T)

        x = self.temp1(x)

        x = x[:, :, -1]

        x = x.view(B, N, -1)

        # ----------------------------------------------------
        # GRAPH
        # ----------------------------------------------------

        x = self.graph1(x, adj)

        x = self.drop(x)

        # ----------------------------------------------------
        # SECOND GRAPH
        # ----------------------------------------------------

        x = self.graph2(x, adj)

        x = self.drop(x)

        # ----------------------------------------------------
        # OUTPUT
        # ----------------------------------------------------

        out = self.fc(x)

        out = out.squeeze(-1)

        return out

