class EngineWindowDataset(Dataset):

    def __init__(self, folder, scaler=None):

        files = sorted([
            f for f in os.listdir(folder)
            if f.endswith(".csv")
        ])

        all_series = []

        for f in files:

            df = pd.read_csv(
                os.path.join(folder, f)
            )

            arr = df.iloc[:,1:].values.astype(np.float32)

            all_series.append(arr)

        # ====================================================
        # SCALER
        # ====================================================

        if scaler is None:

            self.scaler = MinMaxScaler().fit(
                np.vstack(all_series)
            )

        else:

            self.scaler = scaler

        X = []
        Y = []

        # ====================================================
        # WINDOW CREATION
        # ====================================================

        for series in all_series:

            series = self.scaler.transform(series)

            for i in range(
                WARMUP,
                len(series)-WINDOW-HORIZON
            ):

                X.append(
                    series[i:i+WINDOW]
                )

                Y.append(
                    series[i+WINDOW+HORIZON-1]
                )

        self.X = torch.tensor(
            np.array(X),
            dtype=torch.float32
        )

        self.Y = torch.tensor(
            np.array(Y),
            dtype=torch.float32
        )

        print(
            f"Loaded {len(self.X)} windows from {folder}"
        )

    def __len__(self):

        return len(self.X)

    def __getitem__(self, idx):

        return self.X[idx], self.Y[idx]

