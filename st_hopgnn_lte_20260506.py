class ESN(nn.Module):

    def __init__(self, in_dim, hid):

        super().__init__()

        self.Win = nn.Parameter(
            torch.randn(in_dim, hid) * 0.1,
            requires_grad=False
        )

    def forward(self, x):

        return torch.tanh(x @ self.Win)

# ============================================================
