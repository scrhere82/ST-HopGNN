class ESN(nn.Module):

    def __init__(self, in_dim, hid):

        super().__init__()

        self.Win = nn.Parameter(
            torch.randn(in_dim, hid) * 0.1,
            requires_grad=False
        )

    def forward(self, x):

        return torch.tanh(x @ self.Win)

class HopGNN(nn.Module):

    def __init__(self, hid, hops, nodes):

        super().__init__()

        self.convs = nn.ModuleList([

            GCNConv(hid, hid)

            for _ in range(hops)

        ])

        self.emb = nn.Parameter(
            torch.randn(hops, hid)
        )

        self.drop = nn.Dropout(0.35)

    def forward(self, x, adj):

        adj = torch.sigmoid(adj)

        adj = adj * (adj > 0.5)

        edge_index = adj.nonzero().t()

        edge_weight = adj[
            edge_index[0],
            edge_index[1]
        ]

        B, N, H = x.shape

        x = x.view(-1, H)

        outs = []

        for k, conv in enumerate(self.convs):

            x = x + self.emb[k]

            x = conv(
                x,
                edge_index,
                edge_weight
            )

            x = self.drop(x)

            outs.append(x)

        out = torch.mean(
            torch.stack(outs),
            dim=0
        )

        return out.view(B, N, H)

class STHopGNN(nn.Module):

    def __init__(self, nodes, hid=128, hops=4):

        super().__init__()

        self.esn = ESN(1, hid)

        self.gnn = HopGNN(
            hid,
            hops,
            nodes
        )

        self.adj = nn.Parameter(
            torch.rand(nodes, nodes) * 0.1
        )

        self.drop = nn.Dropout(0.35)

        self.recon = nn.Linear(hid, 1)

    def forward(self, x):

        last = x[:, -1, :].unsqueeze(-1)

        feats = torch.cat([

            self.esn(
                last[:, n, :]
            ).unsqueeze(1)

            for n in range(last.shape[1])

        ], 1)

        h = self.gnn(
            feats,
            self.adj
        )

        h = self.drop(h)

        return self.recon(h).squeeze(-1)

