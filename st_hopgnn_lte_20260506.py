class ESN(nn.Module):

    def __init__(self, in_dim, hid_dim):

        super().__init__()

        self.Win = nn.Parameter(
            torch.randn(in_dim, hid_dim)*0.1,
            requires_grad=False
        )

    def forward(self, x):

        return torch.tanh(x @ self.Win)

# ============================================================
# HOPGNN
# ============================================================

class HopGNN(nn.Module):

    def __init__(self, hid, hops):

        super().__init__()

        self.convs = nn.ModuleList([

            GCNConv(hid, hid)

            for _ in range(hops)
        ])

        self.emb = nn.Parameter(
            torch.randn(hops, hid)
        )

        self.drop = nn.Dropout(0.35)

    def forward(self, x, adj):

        B, N, H = x.shape

        # ----------------------------------------------------
        # GRAPH
        # ----------------------------------------------------

        if GRAPH_MODE == "learned":

            adj = torch.sigmoid(adj)

            adj = adj * (adj > 0.5)

        else:

            adj = adj.to(x.device)

        edge_index = adj.nonzero().t()

        edge_weight = adj[
            edge_index[0],
            edge_index[1]
        ]

        # ----------------------------------------------------
        # FLATTEN
        # ----------------------------------------------------

        x = x.view(-1, H)

        outs = []

        for k, conv in enumerate(self.convs):

            x = x + self.emb[k]

            x = conv(
                x,
                edge_index,
                edge_weight
            )

            x = self.drop(x)

            outs.append(x)

        out = torch.mean(
            torch.stack(outs),
            dim=0
        )

        return out.view(B, N, H)

