# AGCRN CELL
# ============================================================

class AGCRNCell(nn.Module):

    def __init__(
        self,
        num_nodes,
        dim_in,
        dim_out,
        cheb_k,
        embed_dim
    ):

        super().__init__()

        self.hidden_dim = dim_out

        self.gate = AVWGCN(
            dim_in + dim_out,
            2 * dim_out,
            cheb_k,
            embed_dim
        )

        self.update = AVWGCN(
            dim_in + dim_out,
            dim_out,
            cheb_k,
            embed_dim
        )

    def forward(
        self,
        x,
        state,
        node_emb
    ):

        """
        x:
            [B,N,C]
        """

        state = state.to(x.device)

        input_and_state = torch.cat(
            [x, state],
            dim=-1
        )

        z_r = torch.sigmoid(
            self.gate(
                input_and_state,
                node_emb
            )
        )

        z, r = torch.split(
            z_r,
            self.hidden_dim,
            dim=-1
        )

        candidate = torch.cat(
            [x, z * state],
            dim=-1
        )

        hc = torch.tanh(
            self.update(
                candidate,
                node_emb
            )
        )

        h = r * state + (1-r) * hc

        return h

