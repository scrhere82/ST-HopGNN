class STGCN(nn.Module):

    def __init__(self, num_sensors, hid=64):

        super().__init__()

        # ----------------------------------------------------
        # NODE-WISE TEMPORAL ENCODER
        # ----------------------------------------------------

        self.temporal = nn.GRU(
            input_size=1,
            hidden_size=hid,
            num_layers=1,
            batch_first=True
        )

        # ----------------------------------------------------
        # GRAPH
        # ----------------------------------------------------

        self.gcn1 = GCNConv(hid, hid)

        self.gcn2 = GCNConv(hid, hid)

        # ----------------------------------------------------
        # OUTPUT
        # ----------------------------------------------------

        self.fc = nn.Sequential(

            nn.Linear(hid, 32),
            nn.ReLU(),

            nn.Linear(32, 1)
        )

        # ----------------------------------------------------
        # FULL GRAPH
        # ----------------------------------------------------

        adj = torch.ones(
            num_sensors,
            num_sensors
        )

        edge_index = adj.nonzero().t()

        self.register_buffer(
            "edge_index",
            edge_index
        )

    def forward(self, x):

        B, T, N = x.shape

        # ----------------------------------------------------
        # NODE-WISE TEMPORAL FEATURES
        # ----------------------------------------------------

        feats = []

        for n in range(N):

            sensor_seq = x[:, :, n].unsqueeze(-1)

            h, _ = self.temporal(sensor_seq)

            feats.append(
                h[:, -1].unsqueeze(1)
            )

        h = torch.cat(feats, dim=1)

        # ----------------------------------------------------
        # GRAPH
        # ----------------------------------------------------

        h = h.view(-1, h.size(-1))

        h = self.gcn1(
            h,
            self.edge_index
        )

        h = torch.relu(h)

        h = self.gcn2(
            h,
            self.edge_index
        )

        h = torch.relu(h)

        # ----------------------------------------------------
        # OUTPUT
        # ----------------------------------------------------

        out = self.fc(h)

        out = out.view(B, N)

        return out

