class TCN(nn.Module):

    def __init__(self, hid):

        super().__init__()

        self.net = nn.Sequential(

            nn.Conv1d(
                1,
                hid,
                kernel_size=3,
                padding=2,
                dilation=2
            ),

            nn.ReLU(),

            nn.Conv1d(
                hid,
                hid,
                kernel_size=3,
                padding=2,
                dilation=2
            ),

            nn.ReLU()
        )

    def forward(self, x):

        x = x.transpose(1,2)

        out = self.net(x)

        return out.transpose(1,2)

# ============================================================
# HOPGNN
# ============================================================

class HopGNN(nn.Module):

    def __init__(self, hid, hops):

        super().__init__()

        self.convs = nn.ModuleList([

            GCNConv(hid, hid)

            for _ in range(hops)
        ])

        self.emb = nn.Parameter(
            torch.randn(hops, hid)
        )

        self.drop = nn.Dropout(0.35)

    def forward(self, x, adj):

        adj = torch.sigmoid(adj)

        adj = adj * (adj > 0.5)

        edge_index = adj.nonzero().t()

        edge_weight = adj[
            edge_index[0],
            edge_index[1]
        ]

        B, N, H = x.shape

        x = x.view(-1, H)

        outs = []

        for k, conv in enumerate(self.convs):

            x = x + self.emb[k]

            x = conv(
                x,
                edge_index,
                edge_weight
            )

            x = self.drop(x)

            outs.append(x)

        out = torch.mean(
            torch.stack(outs),
            dim=0
        )

        return out.view(B, N, H)

