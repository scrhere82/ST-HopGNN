class STHopGNN(nn.Module):

    def __init__(self, nodes):

        super().__init__()

        # ----------------------------------------------------
        # TEMPORAL MODULE
        # ----------------------------------------------------

        if TEMPORAL == "ESN":

            self.temporal = ESN(1, HID)

        elif TEMPORAL == "LSTM":

            self.temporal = nn.LSTM(
                input_size=1,
                hidden_size=HID,
                batch_first=True
            )

        elif TEMPORAL == "GRU":

            self.temporal = nn.GRU(
                input_size=1,
                hidden_size=HID,
                batch_first=True
            )

        elif TEMPORAL == "TCN":

            self.temporal = TCN(HID)

        # ----------------------------------------------------
        # GNN
        # ----------------------------------------------------

        self.gnn = HopGNN(HID, HOPS)

        self.adj = nn.Parameter(
            torch.rand(nodes, nodes)*0.1
        )

        self.recon = nn.Linear(HID, 1)

    def forward(self, x):

        B,T,N = x.shape

        # ----------------------------------------------------
        # ESN
        # ----------------------------------------------------

        if TEMPORAL == "ESN":

            last = x[:, -1, :].unsqueeze(-1)

            feats = self.temporal(last)

        # ----------------------------------------------------
        # LSTM / GRU
        # ----------------------------------------------------

        elif TEMPORAL in ["LSTM", "GRU"]:

            x2 = x.permute(0,2,1)

            x2 = x2.reshape(B*N,T,1)

            out,_ = self.temporal(x2)

            feats = out[:,-1,:]

            feats = feats.reshape(B,N,HID)

        # ----------------------------------------------------
        # TCN
        # ----------------------------------------------------

        elif TEMPORAL == "TCN":

            x2 = x.permute(0,2,1)

            x2 = x2.reshape(B*N,T,1)

            out = self.temporal(x2)

            feats = out[:,-1,:]

            feats = feats.reshape(B,N,HID)

        # ----------------------------------------------------
        # GRAPH
        # ----------------------------------------------------

        h = self.gnn(feats, self.adj)

        out = self.recon(h).squeeze(-1)

        return out

