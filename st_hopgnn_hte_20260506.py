class TemporalBlock(nn.Module):

    def __init__(
        self,
        in_ch,
        out_ch,
        kernel,
        dilation,
        drop=0.3
    ):

        super().__init__()

        pad = (kernel - 1) * dilation

        self.net = nn.Sequential(

            weight_norm(
                nn.Conv1d(
                    in_ch,
                    out_ch,
                    kernel,
                    padding=pad,
                    dilation=dilation
                )
            ),

            nn.ReLU(),
            nn.Dropout(drop),

            weight_norm(
                nn.Conv1d(
                    out_ch,
                    out_ch,
                    kernel,
                    padding=pad,
                    dilation=dilation
                )
            ),

            nn.ReLU(),
            nn.Dropout(drop)
        )

        self.downsample = (

            nn.Conv1d(
                in_ch,
                out_ch,
                1
            )

            if in_ch != out_ch

            else None
        )

    def forward(self, x):

        out = self.net(x)

        out = out[:, :, :x.size(2)]

        res = (
            x
            if self.downsample is None
            else self.downsample(x)
        )

        return torch.relu(out + res)

