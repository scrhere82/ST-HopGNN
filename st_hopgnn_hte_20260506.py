    def __init__(
        self,
        num_nodes,
        input_dim=1,
        hidden_dim=64,
        output_dim=1,
        k=2
    ):

        super().__init__()

        self.hidden_dim = hidden_dim

        self.cell = DCRNNCell(
            input_dim,
            hidden_dim,
            k
        )

        self.proj = nn.Linear(
            hidden_dim,
            output_dim
        )

    def forward(self, x):

        B, T, N = x.shape

        h = torch.zeros(
            B,
            N,
            self.hidden_dim,
            device=x.device
        )

        for t in range(T):

            xt = x[:, t].unsqueeze(-1)

            h = self.cell(
                xt,
                h,
                adj_dcrnn
            )

        out = self.proj(h)

        out = out.squeeze(-1)

        return out

